/** 格式化用户时间，不改变数据库存储时区。 */
export function formatTimestamp(
  value: string | number | Date,
  locale: Locale,
  timeZone = 'Asia/Shanghai',
) {
  return new Intl.DateTimeFormat(locale, {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone,
  }).format(new Date(value))
}

